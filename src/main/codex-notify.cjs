// src/main/codex-notify.cjs
// Non-destructive install plan for the Codex `notify` bridge.
//
// Codex 0.153.x exposes two notification surfaces and this module only
// deals with the one that actually works for Project Mixer:
//
// - `hooks` (feature flag: stable). Reads hooks.json from CODEX_HOME only.
//   Measured: project-level .codex/hooks.json is NOT discovered, and the
//   SessionStart/Stop events never fired in `codex exec` probes.
// - legacy `notify` in ~/.codex/config.toml. Works. Codex appends the
//   payload as the LAST argv element:
//     argv = [program, ...configuredArgs, payloadJson]
//   payload = { type: 'agent-turn-complete', 'thread-id', 'turn-id', cwd,
//               client, 'input-messages', 'last-assistant-message' }
//
// `thread-id` is the resumable session id: it matches the rollout filename
// (sessions/YYYY/MM/DD/rollout-<ts>-<thread-id>.jsonl), which is what
// `codex resume <id>` looks up. Feeding it to Project Mixer therefore makes
// codex tabs resumable, exactly like claude/opencode.
//
// WHY THIS IS NON-DESTRUCTIVE
// `notify` accepts a single program (a list-of-lists is rejected by
// Codex's config parser: "invalid type: sequence, expected a string").
// Users commonly already have something there -- e.g. the Codex Desktop
// computer-use integration -- and overwriting it would silently break it.
// So this module NEVER edits an existing value. It reports `skip` and the
// caller surfaces a warning instead.

const WRAPPER_SOURCE = `#!/usr/bin/env node
// Generated by Project Mixer. Safe to delete; hook:setup recreates it.
//
// Codex \`notify\` bridge. Sends the agent-turn-complete payload to Project
// Mixer's /hook endpoint so codex tabs get unread badges and so the
// resumable session id reaches the renderer.
//
// Chaining: install this INSTEAD of an existing notify program only after
// the user opted in. When it is chained, argv is
//   [node, thisFile, ...previousProgramAndArgs, payloadJson]
// so everything before the last element is the previous command, which
// still receives the payload. Without a previous program configured the
// prefix is empty and only the POST happens.
//
// Inert without PM_HOOK_URL (i.e. when codex runs outside Project Mixer):
// exits 0 immediately, exactly like the Claude Code hook script.
const { spawn } = require('child_process');
const http = require('http');

const argv = process.argv.slice(2);
const payload = argv.length > 0 ? argv[argv.length - 1] : '';
const previousCommand = argv.slice(0, -1);

// Forward to whatever notify program was configured before us, if any.
if (previousCommand.length > 0) {
  try {
    spawn(previousCommand[0], [...previousCommand.slice(1), payload], {
      stdio: 'ignore',
      detached: true,
    }).unref();
  } catch {
    // A broken predecessor must not block our own notification.
  }
}

const hookUrl = process.env.PM_HOOK_URL;
const hookToken = process.env.PM_HOOK_TOKEN;
if (!hookUrl || !hookToken || !payload) process.exit(0);

let event;
try {
  event = JSON.parse(payload);
} catch {
  process.exit(0);
}
if (!event || typeof event !== 'object') process.exit(0);

// Codex's legacy payload uses kebab-case keys and 'type' for the event
// name. Map them onto the canonical shape agent-notification-service.cjs
// already understands, so no new event kinds are needed downstream:
//   type 'agent-turn-complete' -> kind turn_completed
//   thread-id                  -> sessionId (the resumable id)
let body;
try {
  body = JSON.stringify({
    hook_event_type: typeof event.type === 'string' ? event.type : 'agent-turn-complete',
    session_id: typeof event['thread-id'] === 'string' ? event['thread-id'] : undefined,
    cwd: typeof event.cwd === 'string' ? event.cwd : process.cwd(),
    agent_source: 'codex',
    message: typeof event['last-assistant-message'] === 'string'
      ? event['last-assistant-message']
      : undefined,
  });
} catch {
  process.exit(0);
}

// Exiting here would truncate the socket before the request is flushed.
// Wait for the response, but never let a hung endpoint stall codex.
const done = (code) => {
  try { process.exit(code); } catch {}
};

try {
  const target = new URL(hookUrl);
  const req = http.request({
    hostname: target.hostname,
    port: target.port,
    path: target.pathname,
    method: 'POST',
    headers: {
      'Content-Type': 'application/json',
      'Content-Length': Buffer.byteLength(body),
      'X-Project-Mixer-Hook': hookToken,
    },
  }, () => done(0));
  // A dead or busy endpoint must never surface as a codex error.
  req.on('error', () => done(0));
  req.setTimeout(3000, () => { try { req.destroy(); } catch {} done(0); });
  req.write(body);
  req.end();
} catch {
  // Malformed PM_HOOK_URL: stay silent, as the Claude hook script does.
  done(0);
}
`;

// TOML basics used here: a table header is a line whose first
// non-whitespace character is '['. Everything above the first header is
// the top-level key region, which is where `notify` must live.
function splitTopLevelRegion(toml) {
  const lines = toml.split(/\r?\n/);
  const firstHeaderIndex = lines.findIndex((line) => /^\s*\[/.test(line));
  if (firstHeaderIndex === -1) return { topLevel: lines, headerIndex: lines.length };
  return { topLevel: lines.slice(0, firstHeaderIndex), headerIndex: firstHeaderIndex };
}

function findTopLevelNotify(toml) {
  const { topLevel } = splitTopLevelRegion(toml);
  for (const line of topLevel) {
    // `notify` may be bare or quoted. A '#' comment or a key inside a
    // table is not a top-level notify, hence the region limit above.
    const match = line.match(/^\s*"?notify"?\s*=\s*(.+?)\s*(?:#.*)?$/);
    if (match) return match[1];
  }
  return null;
}

// Append `notify = [...]` to the top-level region. Inserting after the last
// top-level assignment keeps the diff minimal and avoids landing inside a
// table, where the key would silently become part of that table.
function insertTopLevelNotify(toml, value) {
  const lines = toml.split(/\r?\n/);
  const { headerIndex } = splitTopLevelRegion(toml);
  let lastAssignment = -1;
  for (let i = 0; i < headerIndex; i += 1) {
    if (/^\s*[^#\s][^=]*=\s*\S/.test(lines[i])) lastAssignment = i;
  }
  const insertAt = lastAssignment >= 0 ? lastAssignment + 1 : 0;
  lines.splice(insertAt, 0, `notify = ${value}`);
  return lines.join('\n');
}

/**
 * Decide what to do about Codex `notify`, without touching the disk.
 *
 * @param {object} options
 * @param {string|null} options.existingToml  current ~/.codex/config.toml, or null when absent
 * @param {string} options.wrapperPath        absolute path the wrapper will be written to
 * @returns {{action: string, toml?: string, existing?: string, note?: string}}
 */
function planCodexNotifyInstall({ existingToml, wrapperPath }) {
  if (typeof wrapperPath !== 'string' || !wrapperPath.trim()) {
    throw new TypeError('planCodexNotifyInstall requires a wrapperPath');
  }
  if (existingToml === null || existingToml === undefined) {
    return {
      action: 'create',
      toml: insertTopLevelNotify('', `["node", ${JSON.stringify(wrapperPath)}]`),
    };
  }
  const existing = findTopLevelNotify(existingToml);
  if (existing !== null) {
    return {
      action: 'skip',
      existing,
      note: 'Codex notify is already configured. Project Mixer did not modify it.',
    };
  }
  return {
    action: 'install',
    toml: insertTopLevelNotify(existingToml, `["node", ${JSON.stringify(wrapperPath)}]`),
  };
}

module.exports = {
  WRAPPER_SOURCE,
  planCodexNotifyInstall,
  findTopLevelNotify,
  insertTopLevelNotify,
};
